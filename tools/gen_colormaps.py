# Generates colors/lut_gen.go (the colormap lookup tables) and
# colors/testdata/colormaps.json (independent samples used by the tests)
# from matplotlib itself, so the tables are matplotlib's, not a transcription.
#
#   uv run --with matplotlib --with numpy python tools/gen_colormaps.py
#
# Run from the repository root.
import json
import subprocess

import matplotlib
import numpy as np

NAMES = ["viridis", "plasma", "inferno", "magma", "cividis", "gray", "coolwarm", "RdBu"]


def main():
    out = []
    out.append("// Code generated by tools/gen_colormaps.py from matplotlib %s. DO NOT EDIT.\n" % matplotlib.__version__)
    out.append("package colors\n")
    out.append("// lutData holds each colormap's 256-entry RGBA lookup table, as floats in")
    out.append("// [0, 1], exactly as matplotlib holds it (Colormap._lut[:256]).")
    out.append("var lutData = map[string][256][4]float64{")
    for name in NAMES:
        cm = matplotlib.colormaps[name]
        cm._init()
        lut = cm._lut[: cm.N]
        assert cm.N == 256, (name, cm.N)
        out.append("\t\"%s\": {" % name)
        for r in lut:
            out.append("\t\t{%s, %s, %s, %s}," % tuple(repr(float(v)) for v in r))
        out.append("\t},")
    out.append("}\n")
    out.append("// namedData maps every colour name matplotlib knows (base, tab: and CSS4)")
    out.append("// to its hex value.")
    out.append("var namedData = map[string]string{")
    allnames = {}
    for table in (matplotlib.colors.CSS4_COLORS, matplotlib.colors.TABLEAU_COLORS):
        allnames.update(table)
    for k, v in matplotlib.colors.BASE_COLORS.items():
        allnames[k] = matplotlib.colors.to_hex(v)
    for k in sorted(allnames):
        out.append("\t\"%s\": \"%s\"," % (k, allnames[k].lower()))
    out.append("}\n")
    with open("colors/lut_gen.go", "w") as f:
        f.write("\n".join(out))
    subprocess.run(["gofmt", "-w", "colors/lut_gen.go"], check=True)

    # Samples through the public call path: floats, bytes, the ends, and the
    # out-of-range values (under/over/bad keep matplotlib's defaults).
    xs = list(np.linspace(0, 1, 1001)) + [-0.5, -1e-9, 1.0 + 1e-9, 2.0, 0.999, 0.99609375, 0.00390625]
    fx = {"version": matplotlib.__version__, "x": [float(x) for x in xs], "maps": {}}
    for name in NAMES:
        cm = matplotlib.colormaps[name]
        fx["maps"][name] = {
            "rgba": [[float(v) for v in cm(x)] for x in xs],
            "bytes": [[int(v) for v in cm(x, bytes=True)] for x in xs],
        }
    # Named colours and the property cycle.
    fx["cycle"] = [matplotlib.colors.to_hex(c["color"]) for c in matplotlib.rcParams["axes.prop_cycle"]]
    names = {}
    for k in list(matplotlib.colors.BASE_COLORS) + list(matplotlib.colors.TABLEAU_COLORS) + list(matplotlib.colors.CSS4_COLORS):
        names[k] = [float(v) for v in matplotlib.colors.to_rgba(k)]
    for k in ["C0", "C1", "C9", "0.5", "#abc", "#aabbcc80", "none"]:
        names[k] = [float(v) for v in matplotlib.colors.to_rgba(k)]
    fx["named"] = names
    with open("colors/testdata/colormaps.json", "w") as f:
        json.dump(fx, f)


if __name__ == "__main__":
    main()
